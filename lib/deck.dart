List<TarotCard> _suitCards(
  String id,
  String name,
  String english,
  List<(String, String, String)> copy,
) => List.generate(
  14,
  (i) => TarotCard(
    '${id}_${_ranks[i]}',
    i < 10 ? '${i + 1}' : _rankEnglish[i],
    '$name${_rankNames[i]}',
    '${_rankEnglish[i]} OF $english',
    copy[i].$1.split(' · '),
    copy[i].$2,
    copy[i].$3,
    '关于${copy[i].$1.split(' · ').first}，你今天可以尝试哪一个具体的小行动？',
    category: name,
  ),
);
